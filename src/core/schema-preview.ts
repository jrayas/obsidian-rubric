/**
 * The read-only property preview: for each type, a file showing what a new note of that type starts with, built
 * from the schema as it is now. Written to `_schema/preview/<type>.yaml` by the plugin and rewritten whenever the
 * schema changes. The schema files stay the only source of truth; nothing is read back from these files.
 */
import { stringify } from 'yaml';
import { newNoteFrontmatter } from './create';
import { ARCHIVED_FIELDS } from './schema-types';
import type { PropertyDef, ResolvedType, SchemaPack } from './schema-types';

export const PREVIEW_FOLDER = 'preview';
/** First line of every generated file, so stale ones can be recognised. */
export const PREVIEW_MARKER = '# Generated by Rubric from the schema files.';

const TERM_LIMIT = 8;

/** Short human text about a value type, for the optional (commented) properties. */
function typeText(def: PropertyDef, pack: SchemaPack): string {
  switch (def.type) {
    case 'string':
      return 'text';
    case 'integer':
      return def.min !== undefined && def.max !== undefined ? `whole number ${def.min} to ${def.max}` : 'whole number';
    case 'boolean':
      return 'true or false';
    case 'date':
      return 'date YYYY-MM-DD';
    case 'datetime':
      return 'local time YYYY-MM-DDTHH:mm';
    case 'url':
      return 'web address';
    case 'link':
      return `link "[[Note]]"${def.allowHeading ? ' (a heading is allowed)' : ''}${def.target ? `, to a ${def.target} note` : ''}`;
    case 'enum':
      return (def.values ?? []).join(' | ');
    case 'list': {
      if (def.items === 'term') {
        const terms = def.vocabulary ? (pack.vocabularies.get(def.vocabulary)?.terms.map((t) => t.term) ?? []) : [];
        const shown = terms.slice(0, TERM_LIMIT).join(', ');
        return `list of controlled terms: ${shown}${terms.length > TERM_LIMIT ? ', …' : ''}`;
      }
      return `list of ${def.items === 'link' ? 'links' : def.items === 'url' ? 'web addresses' : 'text'}${def.target ? ` to ${def.target} notes` : ''}`;
    }
  }
}

/** The comment after a property that is written at creation. */
function startedComment(def: PropertyDef, pack: SchemaPack): string {
  const parts: string[] = [];
  if (def.generated) parts.push('set by the plugin');
  if (def.immutable) parts.push('never changes');
  if (def.required && !def.generated) parts.push('required');
  if (def.valuesFrom === 'registry') parts.push("one of the types in the registry");
  else if (def.type === 'enum' || def.type === 'list' || (def.type === 'integer' && !def.generated)) parts.push(typeText(def, pack));
  return parts.join('; ');
}

const PLACEHOLDERS = { datetime: 'YYYY-MM-DDTHH:mm' } as const;

/** What one type's preview file contains. Deterministic: the same schema always gives the same text. */
export function renderTypePreview(type: ResolvedType, pack: SchemaPack): string {
  // The same function that creates a new note, with stand-ins for what varies per note.
  const fm = newNoteFrontmatter(type, { name: 'Note name', id: `${type.prefix}-YYYY-0001`, now: new Date(2000, 0, 1) });
  if ('created' in fm) fm.created = PLACEHOLDERS.datetime;
  if ('modified' in fm) fm.modified = PLACEHOLDERS.datetime;

  const lines: string[] = [
    PREVIEW_MARKER,
    '# Do not edit this file: it is rewritten whenever the schema changes. Edit the schema files instead.',
    `# This is how a new "${type.name}" note starts (schema version ${type.version}, ID prefix ${type.prefix}).`,
    '# Properties are written in this order, with these starting values. The comment says what is allowed.',
    '',
  ];

  const written: string[] = [];
  for (const def of type.properties) {
    if (!(def.name in fm)) continue;
    const value = stringify({ [def.name]: fm[def.name] }, { lineWidth: 0, flowCollectionPadding: false }).trimEnd();
    const comment = startedComment(def, pack);
    lines.push(comment ? `${value}  # ${comment}` : value);
    written.push(def.name);
  }

  const optional = type.properties.filter((d) => !written.includes(d.name));
  if (optional.length > 0) {
    lines.push('', '# Optional properties: not written until a value is set (by you, or by your breadcrumb plugin where noted).');
    for (const def of optional) {
      const note = def.managedBy === 'external' ? 'written by your breadcrumb plugin' : def.description ? '' : '';
      const detail = [typeText(def, pack), note].filter(Boolean).join('; ');
      lines.push(`# ${def.name}: ${detail}`);
    }
  }
  lines.push('', `# ${ARCHIVED_FIELDS}: added by the plugin when a note changes type, to keep values that no longer apply (never deleted).`);
  return lines.join('\n') + '\n';
}

/** File name inside the preview folder for a type. */
export const previewFileName = (type: string): string => `${type}.yaml`;

/** Every preview file for the pack: file name -> text. */
export function renderAllPreviews(pack: SchemaPack): Map<string, string> {
  const out = new Map<string, string>();
  for (const type of pack.types.values()) out.set(previewFileName(type.name), renderTypePreview(type, pack));
  return out;
}
