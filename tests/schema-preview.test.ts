import { parse } from 'yaml';
import { beforeAll, describe, expect, it } from 'vitest';
import { newNoteFrontmatter } from '../src/core/create';
import { PREVIEW_MARKER, previewFileName, renderAllPreviews, renderTypePreview } from '../src/core/schema-preview';
import type { ResolvedType, SchemaPack } from '../src/core/schema-types';
import { loadPack } from './helpers/pack';

let pack: SchemaPack;
const t = (n: string) => pack.types.get(n) as ResolvedType;
beforeAll(async () => {
  pack = await loadPack();
});

describe('the generated property preview', () => {
  it('shows what a unique ID looks like for a type that has one', () => {
    const lesson = renderTypePreview(t('lesson'), pack);
    expect(lesson).toContain('unique_id: LS-GE-YYYY-0001  # set by the plugin');
    expect(renderTypePreview(t('kb'), pack)).not.toContain('unique_id');
  });

  it('is a valid YAML file whose keys are exactly what a new note of that type starts with, in order', () => {
    for (const type of pack.types.values()) {
      const text = renderTypePreview(type, pack);
      const parsed = parse(text) as Record<string, unknown>;
      const created = newNoteFrontmatter(type, { name: 'x', id: 'x', now: new Date(), allocateUnique: () => 'x' });
      expect(Object.keys(parsed), type.name).toEqual(Object.keys(created));
    }
  });

  it('says it is generated and must not be edited', () => {
    const text = renderTypePreview(t('kb'), pack);
    expect(text.startsWith(PREVIEW_MARKER)).toBe(true);
    expect(text).toContain('Do not edit this file');
  });

  it('shows starting values and what is allowed, for a kb note', () => {
    const text = renderTypePreview(t('kb'), pack);
    expect(text).toContain('type: kb');
    expect(text).toContain('schema: 2  # set by the plugin');
    expect(text).toContain('id: KB-YYYY-0001  # set by the plugin; never changes');
    expect(text).toContain('status: draft  # required; draft | review | published | outdated | archived');
    expect(text).toContain('language: en-GB  # en-GB | en-US | fr | de | es');
    expect(text).toContain('review_cycle: 6-months  # none | 1-month | 3-months | 6-months | yearly');
    expect(text).toContain('created: YYYY-MM-DDTHH:mm  # set by the plugin; never changes');
    expect(text).toContain('modified: YYYY-MM-DDTHH:mm  # set by the plugin');
  });

  it('shows integer ranges and defaults for a task', () => {
    const text = renderTypePreview(t('task'), pack);
    expect(text).toContain('priority: 3  # whole number 1 to 5');
    expect(text).toContain('status: todo  # required; todo | doing | waiting | done | cancelled');
  });

  it('lists the properties that are not written at the start as comments, including where each comes from', () => {
    const text = renderTypePreview(t('kb'), pack);
    expect(text).toContain('# description: text');
    expect(text).toContain('# tags: list of controlled terms: idea, theory, quantum');
    expect(text).toContain('# breadcrumb: text; written by your breadcrumb plugin');
    expect(text).toContain('# source_url: web address');
    expect(text).toContain('# parent: link "[[Note]]"');
    expect(text).toContain('# archived_fields: added by the plugin when a note changes type');
    // optional properties are comments, never real keys
    expect(Object.keys(parse(text) as object)).not.toContain('description');
  });

  it('mentions link targets and headings where the schema has them', () => {
    expect(renderTypePreview(t('task'), pack)).toContain('# project: link "[[Note]]", to a project note');
    expect(renderTypePreview(t('exercise'), pack)).toContain('# technique: link "[[Note]] (a heading is allowed)"'.replace('"[[Note]] (a heading is allowed)"', '"[[Note]]" (a heading is allowed)'));
  });

  it('is deterministic and follows the schema: changing a status value changes the preview', async () => {
    expect(renderTypePreview(t('kb'), pack)).toBe(renderTypePreview(t('kb'), pack));
    const { loadWith } = await import('./helpers/pack');
    const r = await loadWith({ 'types/kb.yaml': (x) => x.replace('values: [draft, review, published, outdated, archived]', 'values: [draft, review, live, archived]') });
    expect(renderTypePreview(r.pack?.types.get('kb') as ResolvedType, r.pack as SchemaPack)).toContain('status: draft  # required; draft | review | live | archived');
  });

  it('makes one file per type, named after the type', () => {
    const all = renderAllPreviews(pack);
    expect([...all.keys()].sort()).toEqual([...pack.typeNames].map(previewFileName).sort());
    expect(previewFileName('kb')).toBe('kb.yaml');
  });
});
